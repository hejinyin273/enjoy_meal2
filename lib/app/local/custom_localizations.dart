  static String getCustomLanguage() {
    if (Language.zh == Conf.selectedLanguage) {
      return 'zh';
    } else if (Language.en == Conf.selectedLanguage) {
      return 'en';
    } else {
      return 'ja';
    }
  }

  static String assignText(Language language, String textKey) {
    String languageKey = 'ja';
    if (Language.zh == language) {
      languageKey = 'zh';
    } else if (Language.en == language) {
      languageKey = 'en';
    }

    return _localizedValues[languageKey]?[textKey]??"";
  }

  static String text(String textKey) {
    return _localizedValues[getCustomLanguage()]?[textKey]??"";
  }
